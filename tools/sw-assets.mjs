// Writes js/sw-assets.js: every file the service worker pre-caches so the app
// can open offline. Run after adding or removing a page, script, style or image:
//   node tools/sw-assets.mjs
// tests/unit/offline-sw.test.cjs fails if the list is out of date.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const walk = (dir) => readdirSync(join(ROOT, dir)).flatMap((f) => {
  const p = join(dir, f);
  return statSync(join(ROOT, p)).isDirectory() ? walk(p) : [p];
});
export function assetList() {
  return ['/index.html', '/manifest.webmanifest',
    ...['pages', 'js', 'css', 'assets'].flatMap(walk)
      .filter((p) => /\.(html|js|css|png|webp|svg|ico|woff2?)$/.test(p) && !p.endsWith('sw-assets.js'))
      .map((p) => '/' + relative(ROOT, join(ROOT, p)).split('\\').join('/')).sort()];
}
export function render(list) {
  return `/* sw-assets.js — GENERATED by tools/sw-assets.mjs; do not edit by hand.
   The files the service worker (sw.js) pre-caches so the app opens offline. */
self.TAQWA_ASSETS = ${JSON.stringify(list, null, 2)};
`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(ROOT, 'js', 'sw-assets.js'), render(assetList()));
  console.log(`js/sw-assets.js: ${assetList().length} files`);
}
